import { build } from 'esbuild'
import { minify } from 'terser'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const intermediate = new URL('../temp/build/worker/', import.meta.url)
await mkdir(intermediate, { recursive: true })

const bundled = await build({
  absWorkingDir: root,
  entryPoints: ['src/typescript/wasm/index.ts'],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2024',
  // The SINGLE_FILE module has no external WASM URL to resolve.
  define: { 'import.meta.url': '"blob:sequencer-worker"' },
})

let code = bundled.outputFiles[0].text
await writeFile(new URL('bundled.js', intermediate), code)
const originalBytes = Buffer.byteLength(code)
for (let round = 0; round < 3; ++round) {
  const result = await minify(code, {
    ecma: 2020,
    toplevel: true,
    compress: { passes: 3 },
    mangle: { toplevel: true },
    format: { comments: false },
  })
  if (!result.code) throw new Error(`Worker minification round ${round + 1} returned no code`)
  code = result.code
}
await writeFile(new URL('minified.js', intermediate), code)
await writeFile(
  new URL('../src/typescript/runtime/source.ts', import.meta.url),
  '// Generated by scripts/build-worker.mjs. Edit wasm/index.ts, then rebuild.\n' +
    `export const workerSource: string = ${JSON.stringify(code)}\n`
)
console.log(`Worker: ${originalBytes} -> ${Buffer.byteLength(code)} bytes; 3 Terser rounds -> runtime/source.ts`)
